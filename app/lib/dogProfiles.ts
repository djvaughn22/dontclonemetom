export const BANNED_HERO_SPELLINGS = ["bruze zayne", "bruiser"];

function humorStrings(p: DogProfileV1): string[] {
  return [
    ...p.intro,
    ...p.cards.flatMap((c) => [c.nickname, ...c.sayings]),
    p.shareText,
    p.seoTitle,
    p.seoDescription,
  ];
}

// Returns every humor string that smuggles in a real-world claim. Must be
// empty for every shipped profile.
export function findUnverifiedClaims(p: DogProfileV1): string[] {
  return humorStrings(p).filter((s) => {
    const low = s.toLowerCase();
    return CLAIM_TERMS.some((term) => low.includes(term));
  });
}

// Returns every profile string containing a banned public phrase.
export function findBannedPublicPhrases(p: DogProfileV1): string[] {
  const all = JSON.stringify(p).toLowerCase();
  return BANNED_PUBLIC_PHRASES.filter((phrase) => all.includes(phrase));
}

export function findBannedHeroSpellings(p: DogProfileV1): string[] {
  const all = JSON.stringify(p).toLowerCase();
  return BANNED_HERO_SPELLINGS.filter((s) => all.includes(s));
}

// Deck problems for a profile — locked decks skip the name-connection rule
// (a human made each name personal) but never the count/dupe/filler rules.
export function findProfileDeckProblems(p: DogProfileV1): string[] {
  const problems = findDeckProblems(p.cards, { realName: p.realName, locked: true });
  if (p.cards.length !== DECK_SIZE) return problems; // count problem already reported
  if (p.cards[0].nickname !== p.featuredNickname) {
    problems.push(`hero card is ${p.cards[0].nickname}, expected ${p.featuredNickname}`);
  }
  return problems;
}

