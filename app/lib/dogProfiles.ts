export function getDogProfile(slug: string): DogProfileV1 | null {
  // All-digit paths are live rescue listings, never local profiles.
  if (/^\d+$/.test(slug)) return null;
  return PROFILES[slug.toLowerCase()] ?? null;
}

export function listDogProfiles(): DogProfileV1[] {
  return Object.values(PROFILES);
}
